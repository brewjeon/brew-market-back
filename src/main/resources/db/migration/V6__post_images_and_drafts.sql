CREATE TABLE brew_market.post_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES brew_market.posts(id) ON DELETE CASCADE,
    image_key VARCHAR(100) NOT NULL UNIQUE,
    position INTEGER NOT NULL,
    CONSTRAINT ck_post_image_position CHECK (position BETWEEN 0 AND 4),
    CONSTRAINT uq_post_image_position UNIQUE (post_id, position)
);

INSERT INTO brew_market.post_images (post_id, image_key, position)
SELECT id, image_key, 0 FROM brew_market.posts WHERE image_key IS NOT NULL;

CREATE TABLE brew_market.post_drafts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id BIGINT NOT NULL REFERENCES brew_market.users(id),
    title VARCHAR(100),
    description TEXT,
    price BIGINT,
    updated_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_post_draft_price CHECK (price IS NULL OR price >= 0)
);
CREATE INDEX idx_post_drafts_seller ON brew_market.post_drafts (seller_id, updated_at DESC);
CREATE INDEX idx_post_drafts_expiry ON brew_market.post_drafts (expires_at);

CREATE TABLE brew_market.post_draft_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    draft_id BIGINT NOT NULL REFERENCES brew_market.post_drafts(id) ON DELETE CASCADE,
    image_key VARCHAR(100) NOT NULL UNIQUE,
    position INTEGER NOT NULL,
    CONSTRAINT ck_draft_image_position CHECK (position BETWEEN 0 AND 4),
    CONSTRAINT uq_draft_image_position UNIQUE (draft_id, position)
);
